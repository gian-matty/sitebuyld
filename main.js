const STORAGE_KEY = "sitebuyld.lang";

function currentLang() {
  let stored = null;
  try {
    stored = localStorage.getItem(STORAGE_KEY);
  } catch (e) {
    stored = null;
  }
  return stored && I18N[stored] ? stored : "en";
}

function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const val = dict[el.dataset.i18n];
    if (val !== undefined) el.textContent = val;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    const val = dict[el.dataset.i18nPh];
    if (val !== undefined) el.setAttribute("placeholder", val);
  });
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-pressed", active ? "true" : "false");
  });
  document.getElementById("contactForm").querySelector("label.form-note span").textContent =
    dict["form.extra"];
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch (e) {}
}

document.querySelectorAll(".lang-btn").forEach((btn) => {
  btn.addEventListener("click", () => applyLang(btn.dataset.lang));
});

function easeOutCubic(t) {
  return 1 - Math.pow(1 - t, 3);
}

function runCount(stat, index) {
  const el = stat.querySelector(".s-value");
  const target = parseFloat(stat.dataset.target);
  const decimals = parseInt(stat.dataset.decimals || "0", 10);
  const suffix = stat.dataset.suffix || "";

  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    el.textContent = target.toFixed(decimals) + suffix;
    return;
  }

  const duration = 1500 + index * 80;
  const startDelay = 480 + index * 90;
  const start = performance.now() + startDelay;

  function frame(now) {
    if (now < start) {
      requestAnimationFrame(frame);
      return;
    }
    const t = Math.min((now - start) / duration, 1);
    const val = target * easeOutCubic(t);
    el.textContent = val.toFixed(decimals) + suffix;
    if (t < 1) requestAnimationFrame(frame);
  }

  requestAnimationFrame(frame);
}

(() => {
  const stats = document.querySelectorAll(".stat");
  if (!("IntersectionObserver" in window)) {
    stats.forEach((s, i) => runCount(s, i));
    return;
  }
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        const stat = entry.target;
        runCount(stat, parseInt(stat.dataset.index || "0", 10));
        io.unobserve(stat);
      });
    },
    { threshold: 0.25 }
  );
  stats.forEach((s, i) => {
    s.dataset.index = String(i);
    io.observe(s);
  });
})();

